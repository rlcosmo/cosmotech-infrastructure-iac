"""Loopback-only portal behind the existing TLS proxy; no infrastructure writes."""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import re
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Type


def handler(directory: Path, page: Path, credential_digest: str) -> Type[BaseHTTPRequestHandler]:
    """Require SHA256(user:password) provisioned outside Git/Terraform state."""
    if not re.fullmatch(r"[0-9a-f]{64}", credential_digest):
        raise ValueError("A credential digest is required")

    class PortalHandler(BaseHTTPRequestHandler):
        def log_message(self, *_: object) -> None:
            pass  # Never log credentials, paths supplied by clients or evidence.

        def do_GET(self) -> None:
            authorization = self.headers.get("Authorization", "")
            try:
                scheme, encoded = authorization.split(" ", 1)
                credential = base64.b64decode(encoded, validate=True)
                authenticated = scheme == "Basic" and hmac.compare_digest(
                    hashlib.sha256(credential).hexdigest(), credential_digest)
            except (ValueError, TypeError):
                authenticated = False
            if not authenticated:
                self.send_response(401)
                self.send_header("WWW-Authenticate", 'Basic realm="CosmoTech IaC", charset="UTF-8"')
                self.end_headers()
                return
            if self.path == "/":
                body, content_type = page.read_bytes(), "text/html; charset=utf-8"
            elif self.path == "/api/history":
                # Only reports generated by CI belong here; never serve raw state.
                reports = []
                try:
                    for file in sorted(directory.glob("report-*.json"))[-56:]:
                        report = json.loads(file.read_text())
                        if report.get("schema_version") != 1:
                            raise ValueError("Unsupported report")
                        reports.append(report)
                    body = json.dumps(reports).encode()
                except (OSError, ValueError):
                    self.send_error(503, "Evidence unavailable")
                    return
                content_type = "application/json"
            else:
                self.send_error(404)
                return
            self.send_response(200)
            for key, value in {"Content-Type": content_type, "Content-Length": str(len(body)),
                               "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff",
                               "X-Frame-Options": "DENY", "Referrer-Policy": "no-referrer"}.items():
                self.send_header(key, value)
            self.end_headers()
            self.wfile.write(body)

    return PortalHandler


def serve(directory: Path, page: Path, credential_digest: str) -> None:
    """Bind only loopback; TLS terminates at the authorized existing proxy."""
    ThreadingHTTPServer(("127.0.0.1", 8091), handler(directory, page, credential_digest)).serve_forever()
