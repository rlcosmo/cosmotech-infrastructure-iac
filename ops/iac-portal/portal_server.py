"""Loopback-only portal behind the existing TLS proxy; no infrastructure writes."""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
from datetime import datetime, timezone
import re
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Type


def handler(directory: Path, page: Path, credential_digest: str, comparison: Path | None = None, queue: Path | None = None) -> Type[BaseHTTPRequestHandler]:
    """Require SHA256(user:password) provisioned outside Git/Terraform state."""
    if not re.fullmatch(r"[0-9a-f]{64}", credential_digest):
        raise ValueError("A credential digest is required")

    class PortalHandler(BaseHTTPRequestHandler):
        def log_message(self, *_: object) -> None:
            pass  # Never log credentials, paths supplied by clients or evidence.

        def authenticate(self) -> bool:
            authorization = self.headers.get("Authorization", "")
            try:
                scheme, encoded = authorization.split(" ", 1)
                credential = base64.b64decode(encoded, validate=True)
                authenticated = scheme == "Basic" and hmac.compare_digest(
                    hashlib.sha256(credential).hexdigest(), credential_digest)
            except (ValueError, TypeError):
                authenticated = False
            if not authenticated:
                self.send_response(401)
                self.send_header("WWW-Authenticate", 'Basic realm="CosmoTech IaC", charset="UTF-8"')
                self.end_headers()
                return False
            return True

        def do_GET(self) -> None:
            if not self.authenticate():
                return
            if self.path == "/":
                body, content_type = page.read_bytes(), "text/html; charset=utf-8"
            elif self.path == "/api/comparison":
                try:
                    snapshot = json.loads((comparison / 'current.json').read_text()) if comparison else {}
                    if snapshot.get('schema_version') != 2:
                        raise ValueError('Invalid comparison')
                    if snapshot.get('state') == 'ready':
                        age = (datetime.now(timezone.utc) - datetime.fromisoformat(snapshot['observed_at'])).total_seconds()
                        if age > 900:
                            snapshot['state'] = 'stale'
                    body = json.dumps(snapshot).encode()
                except (OSError, ValueError, TypeError, KeyError):
                    body = json.dumps({'schema_version':2,'state':'starting','resources':[],'coverage':[]}).encode()
                content_type = 'application/json'
            elif self.path == "/api/history":
                # Only reports generated by CI belong here; never serve raw state.
                reports = []
                try:
                    for file in sorted(directory.glob("report-*.json"))[-56:]:
                        report = json.loads(file.read_text())
                        if report.get("schema_version") != 1:
                            raise ValueError("Unsupported report")
                        reports.append(report)
                    body = json.dumps(reports).encode()
                except (OSError, ValueError):
                    self.send_error(503, "Evidence unavailable")
                    return
                content_type = "application/json"
            else:
                self.send_error(404)
                return
            self.send_response(200)
            for key, value in {"Content-Type": content_type, "Content-Length": str(len(body)),
                               "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff",
                               "X-Frame-Options": "DENY", "Referrer-Policy": "no-referrer"}.items():
                self.send_header(key, value)
            self.end_headers()
            self.wfile.write(body)

        def do_POST(self) -> None:
            if not self.authenticate():
                return
            if self.path != '/api/refresh':
                self.send_error(501)
                return
            if queue is None or not queue.is_dir():
                self.send_error(503, 'Observer unavailable')
                return
            try:
                descriptor = os.open(queue / 'refresh.request', os.O_CREAT | os.O_EXCL | os.O_WRONLY | os.O_NOFOLLOW, 0o660)
                os.close(descriptor)
            except FileExistsError:
                pass
            except OSError:
                self.send_error(503, 'Observer unavailable')
                return
            self.send_response(202)
            self.send_header('Content-Type', 'application/json')
            self.send_header('Cache-Control', 'no-store')
            self.end_headers()
            self.wfile.write(b'{"queued":true}')

    return PortalHandler


def serve(directory: Path, page: Path, credential_digest: str) -> None:
    """Bind only loopback; TLS terminates at the authorized existing proxy."""
    ThreadingHTTPServer(("127.0.0.1", 8091), handler(directory, page, credential_digest, Path('/var/lib/cosmotech-iac/comparison'), Path('/run/cosmotech-iac-observer'))).serve_forever()
